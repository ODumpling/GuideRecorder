# Replays a GuideRecorder guide on Windows through UI Automation.
#
#   powershell -ExecutionPolicy Bypass -File replay.ps1 -DryRun    report only, change nothing
#   powershell -ExecutionPolicy Bypass -File replay.ps1            do the steps
#
# Options:
#   -DryRun     Look up every step's app, window and element and report
#               what would be done; press, type and activate nothing.
#   -From N     Start at step N (e.g. after doing a step by hand).
#   -To N       Stop after step N.
#   -Delay S    Seconds to wait after each step (default 1).
#   -Help       Show how to run it.
#
# Each step's element is found through UI Automation: the app's processes
# (by executable name, else by name), then its top-level window (by
# title), then an element of the recorded role whose name, help text,
# label or value is the recorded label. Roles are stored as AX role names
# (AXButton, AXTextField, ...); each stands for the UI Automation control
# types the recorder maps onto it. Menu items, and elements recorded
# without a window, are looked for in all of the app's windows, as menus
# open in windows of their own.
#
# Clicks invoke the element (or toggle, select, expand or collapse it,
# whichever it supports; an element with none of these is focused),
# right-clicks focus it and press Shift+F10 to show its menu, typing
# focuses it and types the text, shortcuts press the keys in the app's
# window. Keys are sent with SendInput, so any text and the Windows key
# work whatever the keyboard layout.
#
# The script stops, without acting, at the first step it can't do safely:
# an element that was not identified clearly when recorded, an app, window
# or element it can't find, more than one matching element, a password
# (masked when recorded), a manual step, a double-click, a drag, a key it
# doesn't know or a window it can't bring to the front. Do that step by
# hand, then run again with -From and the next step's number. It exits
# with code 1 when it stops.
#
# Windows keeps a script from controlling an app that runs as
# administrator unless the script does too. A dry run of a guide only
# finds the elements already on screen; later steps' elements often
# appear only after earlier steps are done.
#
# Generated by GuideRecorder from the guide below; edit with care.

[CmdletBinding()]
param(
    [switch]$DryRun,
    [ValidateRange(0, 2147483647)][int]$From = 1,
    [ValidateRange(0, 2147483647)][int]$To = 2147483647,
    [ValidateRange(0, 86400)][double]$Delay = 1,
    [switch]$Help
)

