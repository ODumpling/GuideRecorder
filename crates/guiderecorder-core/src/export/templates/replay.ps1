# Without the client-side providers every classic Win32 or Windows Forms
# control looks like a pane. They load on first use, but that fails when
# the caller is PowerShell (it looks for the calling assembly on the
# stack), and the failed attempt marks them loaded; registering them again
# then works.
try {
    Add-Type -AssemblyName UIAutomationClientsideProviders
    $providers = [UIAutomationClientsideProviders.UIAutomationClientSideProviders].Assembly.GetName()
    try {
        [System.Windows.Automation.ClientSettings]::RegisterClientSideProviderAssembly($providers)
    } catch {
        [System.Windows.Automation.ClientSettings]::RegisterClientSideProviderAssembly($providers)
    }
} catch {
    Write-Warning "Classic Windows controls may not be found: $($_.Exception.Message)"
}

if (-not ('GuideRecorderReplay.Native' -as [type])) {
    Add-Type -TypeDefinition @'
using System;
using System.Runtime.InteropServices;
using System.Threading;

namespace GuideRecorderReplay {
    public static class Native {
        [StructLayout(LayoutKind.Sequential)]
        struct MOUSEINPUT { public int dx, dy; public uint mouseData, dwFlags, time; public IntPtr extra; }
        [StructLayout(LayoutKind.Sequential)]
        struct KEYBDINPUT { public ushort wVk, wScan; public uint dwFlags, time; public IntPtr extra; }
        [StructLayout(LayoutKind.Explicit)]
        struct UNION { [FieldOffset(0)] public MOUSEINPUT mi; [FieldOffset(0)] public KEYBDINPUT ki; }
        [StructLayout(LayoutKind.Sequential)]
        struct INPUT { public uint type; public UNION u; }

        const uint INPUT_KEYBOARD = 1, KEYUP = 2, UNICODE = 4, EXTENDED = 1;

        [DllImport("user32.dll", SetLastError = true)]
        static extern uint SendInput(uint count, INPUT[] inputs, int size);
        [DllImport("user32.dll")] static extern uint MapVirtualKey(uint code, uint type);
        [DllImport("user32.dll")] static extern short VkKeyScan(char c);
        [DllImport("user32.dll")] public static extern IntPtr GetForegroundWindow();
        [DllImport("user32.dll")] static extern bool SetForegroundWindow(IntPtr window);
        [DllImport("user32.dll")] static extern bool ShowWindow(IntPtr window, int command);
        [DllImport("user32.dll")] static extern bool IsIconic(IntPtr window);
        [DllImport("user32.dll")] static extern IntPtr GetAncestor(IntPtr window, uint flags);
        [DllImport("user32.dll")] static extern uint GetWindowThreadProcessId(IntPtr window, out uint pid);
        [DllImport("user32.dll")] static extern bool AttachThreadInput(uint from, uint to, bool attach);
        [DllImport("kernel32.dll")] static extern uint GetCurrentThreadId();

        static INPUT Key(ushort vk, ushort scan, uint flags) {
            INPUT input = new INPUT();
            input.type = INPUT_KEYBOARD;
            input.u.ki.wVk = vk;
            input.u.ki.wScan = scan;
            input.u.ki.dwFlags = flags;
            return input;
        }

        static void Send(INPUT[] inputs) {
            uint sent = SendInput((uint)inputs.Length, inputs, Marshal.SizeOf(typeof(INPUT)));
            if (sent != inputs.Length) throw new InvalidOperationException("Windows blocked the key presses (is the app running as administrator?)");
        }

        // The navigation keys, which need the extended flag.
        static bool IsExtended(ushort vk) {
            return (vk >= 0x21 && vk <= 0x28) || vk == 0x2D || vk == 0x2E || vk == 0x5B;
        }

        static INPUT VirtualKey(ushort vk, bool up) {
            uint flags = (up ? KEYUP : 0) | (IsExtended(vk) ? EXTENDED : 0);
            return Key(vk, (ushort)MapVirtualKey(vk, 0), flags);
        }

        // Holds `modifiers`, presses `vk` and lets go again.
        public static void Press(int[] modifiers, int vk) {
            var inputs = new System.Collections.Generic.List<INPUT>();
            foreach (int m in modifiers) inputs.Add(VirtualKey((ushort)m, false));
            inputs.Add(VirtualKey((ushort)vk, false));
            inputs.Add(VirtualKey((ushort)vk, true));
            for (int i = modifiers.Length - 1; i >= 0; i--) inputs.Add(VirtualKey((ushort)modifiers[i], true));
            Send(inputs.ToArray());
        }

        // Types `text` as characters, whatever the keyboard layout; line
        // breaks and tabs as their keys.
        public static void Type(string text) {
            for (int i = 0; i < text.Length; i++) {
                char c = text[i];
                if (c == '\r' && i + 1 < text.Length && text[i + 1] == '\n') continue;
                if (c == '\r' || c == '\n') { Press(new int[0], 0x0D); continue; }
                if (c == '\t') { Press(new int[0], 0x09); continue; }
                Send(new INPUT[] { Key(0, c, UNICODE), Key(0, c, UNICODE | KEYUP) });
                Thread.Sleep(5);
            }
        }

        // The virtual key and the shift state (1 Shift, 2 Ctrl, 4 Alt) that
        // type `c` on this keyboard layout; -1 if no key does.
        public static int KeyFor(char c) {
            return VkKeyScan(c);
        }

        // The id of the process whose window is in front; 0 if none.
        public static int ForegroundProcess() {
            uint pid;
            GetWindowThreadProcessId(GetForegroundWindow(), out pid);
            return (int)pid;
        }

        static bool IsFront(IntPtr window) {
            IntPtr front = GetForegroundWindow();
            return front == window || GetAncestor(front, 2) == window;
        }

        // Brings `window` to the front; false if Windows didn't let it.
        public static bool Activate(IntPtr window) {
            if (IsIconic(window)) ShowWindow(window, 9);
            if (SetForegroundWindow(window) && IsFront(window)) return true;
            // Windows only lets the app in front hand over the foreground:
            // share its input state for the moment.
            uint ignored;
            uint front = GetWindowThreadProcessId(GetForegroundWindow(), out ignored);
            uint self = GetCurrentThreadId();
            if (front != 0 && front != self && AttachThreadInput(self, front, true)) {
                SetForegroundWindow(window);
                AttachThreadInput(self, front, false);
            }
            Thread.Sleep(100);
            return IsFront(window);
        }
    }
}
'@
}

$UIA = [System.Windows.Automation.AutomationElement]

function Stop-Step([string]$message) {
    throw [System.InvalidOperationException]::new($message)
}

# Collapses whitespace, as the recorder cleans labels.
function Get-Clean($text) {
    if ($null -eq $text) { return '' }
    return (([string]$text) -replace '\s+', ' ').Trim()
}

# The text as the recorder stores it: cleaned and cut at 200 characters
# with an ellipsis.
function Get-Cut($text) {
    $text = Get-Clean $text
    $count = 0
    for ($i = 0; $i -lt $text.Length; $i++) {
        if ($count -eq 200) { return $text.Substring(0, $i).TrimEnd() + [char]0x2026 }
        if ([char]::IsHighSurrogate($text[$i]) -and $i + 1 -lt $text.Length) { $i++ }
        $count++
    }
    return $text
}

# Calls `get` and returns its value, or $null if the element doesn't have it.
function Get-Attempt([scriptblock]$get) {
    try { return & $get } catch { return $null }
}

function Get-Quoted([string]$text) {
    $escaped = $text.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n').Replace("`t", '\t')
    return '"' + $escaped + '"'
}

function Get-Description($step) {
    $el = $step.element
    if (-not $el) { return '' }
    $parts = @()
    if ($el.role -or $el.label) {
        $role = if ($el.role) { $el.role } else { 'element' }
        if ($el.label) { $role = "$role $(Get-Quoted $el.label)" }
        $parts += $role
    }
    if ($el.window) { $parts += "in window $(Get-Quoted $el.window)" }
    if ($el.app -or $el.bundleId) { $parts += "of $(if ($el.app) { $el.app } else { $el.bundleId })" }
    return $parts -join ' '
}

function Get-KeysText($keys) {
    if (-not $keys) { return '' }
    if ($keys.type -eq 'text') { return "type $(Get-Quoted $keys.text)$(if ($keys.submit) { ' and press Enter' })" }
    if ($keys.type -eq 'secret') { return 'type a password' }
    $key = [string]$keys.key
    $key = if ($KeyNames.ContainsKey($key)) { $KeyNames[$key] } else { $key.ToUpperInvariant() }
    $names = @($keys.modifiers | ForEach-Object { $ModifierNames[$_] }) + @($key)
    return "press $($names -join '+')"
}

# What the step does, in words.
function Get-Plan($step) {
    $target = Get-Description $step
    switch ($step.kind) {
        'click' { return "click $target" }
        'rightClick' { return "show the menu of $target" }
        'type' { return "$(Get-KeysText $step.keys) into $target" }
        'shortcut' {
            $keys = Get-KeysText $step.keys
            if (-not $keys) { $keys = "press $(if ($step.keystrokes) { $step.keystrokes } else { '?' })" }
            if ($target) { return "$keys in $($target -replace '^of ', '')" }
            return $keys
        }
        'doubleClick' { return "double-click $target" }
        'drag' { return "drag $target" }
        default { return 'do it by hand' }
    }
}

# The virtual key and modifiers that press a shortcut, or $null if no key
# on this keyboard does.
function Get-Chord($keys) {
    $mods = @($keys.modifiers | ForEach-Object { $ModifierKeys[$_] })
    $key = [string]$keys.key
    if ($VirtualKeys.ContainsKey($key)) { return @{ Modifiers = $mods; Key = $VirtualKeys[$key] } }
    if ($key.Length -ne 1) { return $null }
    $c = [int]$key[0]
    # Letters and digits are their own virtual keys (A is 0x41).
    if ($c -ge 0x61 -and $c -le 0x7A) { return @{ Modifiers = $mods; Key = $c - 0x20 } }
    if ($c -ge 0x30 -and $c -le 0x39) { return @{ Modifiers = $mods; Key = $c } }
    $scan = [int][GuideRecorderReplay.Native]::KeyFor($key[0])
    if ($scan -eq -1 -or ($scan -band 0x600)) { return $null }
    # A character typed with Shift (e.g. "+") holds Shift too.
    if (($scan -band 0x100) -and -not ($mods -contains 0x10)) { $mods += 0x10 }
    return @{ Modifiers = $mods; Key = $scan -band 0xFF }
}

# Why the step can't be replayed at all, or $null.
function Get-Unsupported($step) {
    if ($step.kind -eq 'manual') { return 'it is a manual step' }
    if ($step.kind -eq 'doubleClick') { return 'double-clicks are not replayed' }
    if ($step.kind -eq 'drag') { return 'drags are not replayed' }
    if ($step.keys -and $step.keys.type -eq 'secret') { return 'it types a password, which was masked when recorded' }
    if (($step.kind -eq 'type' -or $step.kind -eq 'shortcut') -and -not $step.keys) {
        return "its keys ($(if ($step.keystrokes) { $step.keystrokes } else { 'none' })) can't be read"
    }
    if ($step.keys -and $step.keys.type -eq 'shortcut' -and -not (Get-Chord $step.keys)) {
        return "the key $($step.keys.key) is not known"
    }
    if ($step.confidence.level -eq 'low') { return "its element is unclear ($($step.confidence.issues -join ', '))" }
    if ($step.kind -eq 'shortcut' -and -not (Get-KeysApp $step)) { return "it doesn't say which app gets the keys" }
    return $null
}

# The element whose app gets a shortcut's keys: the step's, else the
# nearest earlier step's.
function Get-KeysApp($step) {
    $app = $null
    foreach ($s in @($Guide.steps)) {
        if ($s.number -gt $step.number) { break }
        if ($s.element -and ($s.element.bundleId -or $s.element.app)) { $app = $s.element }
    }
    return $app
}

# The running processes of the element's app.
function Find-Processes($el) {
    $all = [System.Diagnostics.Process]::GetProcesses()
    if ($el.bundleId) {
        return @($all | Where-Object { ($_.ProcessName + '.exe') -ieq $el.bundleId -or $_.ProcessName -ieq $el.bundleId })
    }
    return @($all | Where-Object {
        $p = $_
        $p.ProcessName -ieq $el.app -or (Get-Attempt { $p.MainModule.FileVersionInfo.FileDescription }) -ieq $el.app
    })
}

# The top-level windows of `processes`.
function Find-Windows($processes) {
    $conditions = [System.Windows.Automation.Condition[]]@($processes | ForEach-Object {
        [System.Windows.Automation.PropertyCondition]::new($UIA::ProcessIdProperty, [int]$_.Id)
    })
    $condition = if ($conditions.Count -eq 1) { $conditions[0] } else { [System.Windows.Automation.OrCondition]::new($conditions) }
    return @($UIA::RootElement.FindAll([System.Windows.Automation.TreeScope]::Children, $condition))
}

function Get-ControlTypes([string]$role) {
    $names = $RoleControlTypes[$role]
    # A UI Automation control type name (Button, ControlType.Button) stands for itself.
    if (-not $names -and $role) { $names = @($role -replace '^ControlType\.', '') }
    $types = @()
    foreach ($name in @($names)) {
        try { $type = [System.Windows.Automation.ControlType]::$name } catch { $type = $null }
        if ($type -is [System.Windows.Automation.ControlType]) { $types += $type }
    }
    return , $types
}

function Test-Label($candidate, [string]$label) {
    $getters = @(
        { $candidate.Current.Name },
        { $candidate.Current.HelpText },
        { $candidate.Current.LabeledBy.Current.Name },
        {
            if ($candidate.Current.IsPassword) { return $null }
            $pattern = $null
            if ($candidate.TryGetCurrentPattern([System.Windows.Automation.ValuePattern]::Pattern, [ref]$pattern)) { $pattern.Current.Value }
        }
    )
    foreach ($get in $getters) {
        # Labels are cut at 200 characters when recorded.
        $text = Get-Cut (Get-Attempt $get)
        if ($text -ne '' -and $text -ceq $label) { return $true }
    }
    return $false
}

# The elements in `roots` that match the step's role and label, each with
# the root it is in.
function Find-Elements($roots, $el) {
    $label = Get-Clean $el.label
    $types = Get-ControlTypes $el.role
    if ($types.Count -eq 0) { return @() }
    $conditions = [System.Windows.Automation.Condition[]]@($types | ForEach-Object {
        [System.Windows.Automation.PropertyCondition]::new($UIA::ControlTypeProperty, $_)
    })
    $condition = if ($conditions.Count -eq 1) { $conditions[0] } else { [System.Windows.Automation.OrCondition]::new($conditions) }
    $found = @()
    foreach ($root in $roots) {
        $all = Get-Attempt { $root.FindAll([System.Windows.Automation.TreeScope]::Subtree, $condition) }
        foreach ($candidate in @($all)) {
            if ($candidate -and (Test-Label $candidate $label)) { $found += , @($candidate, $root) }
        }
    }
    return , $found
}

# The top-level window of the element's app called as recorded, else its
# front window; $null if it has none.
function Find-AppWindow($el) {
    $processes = @(Find-Processes $el)
    if ($processes.Count -eq 0) { return $null }
    $windows = @(Find-Windows $processes)
    $title = Get-Clean $el.window
    if ($title -ne '') {
        $named = @($windows | Where-Object { (Get-Cut (Get-Attempt { $_.Current.Name })) -ceq $title })
        if ($named.Count -eq 1) { return $named[0] }
    }
    foreach ($process in $processes) {
        $handle = Get-Attempt { $process.MainWindowHandle }
        if ($handle -and $handle -ne [IntPtr]::Zero) { return $UIA::FromHandle($handle) }
    }
    if ($windows.Count -gt 0) { return $windows[0] }
    return $null
}

# Looks the step's element up. Returns @{ Element; Window } or @{ Problem };
# never activates anything.
function Find-Element($step) {
    $el = $step.element
    $app = if ($el.app) { $el.app } else { $el.bundleId }
    $processes = @(Find-Processes $el)
    if ($processes.Count -eq 0) { return @{ Problem = "$app is not running" } }
    $windows = @(Find-Windows $processes)
    $title = Get-Clean $el.window
    $menu = $MenuRoles -contains $el.role
    if ($menu -or $title -eq '') {
        $roots = $windows
    } else {
        $roots = @($windows | Where-Object { (Get-Cut (Get-Attempt { $_.Current.Name })) -ceq $title })
        if ($roots.Count -eq 0) { return @{ Problem = "no window $(Get-Quoted $title) is open" } }
        if ($roots.Count -gt 1) { return @{ Problem = "$($roots.Count) windows are called $(Get-Quoted $title)" } }
    }
    if ((Get-ControlTypes $el.role).Count -eq 0) { return @{ Problem = "the role $($el.role) is not known" } }
    $found = Find-Elements $roots $el
    if ($found.Count -eq 0) { return @{ Problem = 'the element is not there' } }
    if ($found.Count -gt 1) { return @{ Problem = "$($found.Count) elements match" } }
    # An open menu closes when its app's window is brought to the front.
    $window = if ($menu) { $null } else { $found[0][1] }
    return @{ Element = $found[0][0]; Window = $window }
}

function Show-Window($window) {
    if (-not $window) { return }
    $handle = [IntPtr](Get-Attempt { $window.Current.NativeWindowHandle })
    if ($handle -eq [IntPtr]::Zero) {
        Get-Attempt { $window.SetFocus() } | Out-Null
    } elseif (-not [GuideRecorderReplay.Native]::Activate($handle)) {
        Get-Attempt { $window.SetFocus() } | Out-Null
        Start-Sleep -Milliseconds 200
        if (-not [GuideRecorderReplay.Native]::Activate($handle)) {
            Stop-Step "its window $(Get-Quoted (Get-Attempt { $window.Current.Name })) can't be brought to the front"
        }
    }
    Start-Sleep -Milliseconds 500
}

function Get-Pattern($element, $pattern) {
    $found = $null
    if ($element.TryGetCurrentPattern($pattern, [ref]$found)) { return $found }
    return $null
}

# Presses the element the way it supports.
function Invoke-Element($element) {
    $invoke = Get-Pattern $element ([System.Windows.Automation.InvokePattern]::Pattern)
    if ($invoke) { $invoke.Invoke(); return }
    $toggle = Get-Pattern $element ([System.Windows.Automation.TogglePattern]::Pattern)
    if ($toggle) { $toggle.Toggle(); return }
    $select = Get-Pattern $element ([System.Windows.Automation.SelectionItemPattern]::Pattern)
    if ($select) { $select.Select(); return }
    $expand = Get-Pattern $element ([System.Windows.Automation.ExpandCollapsePattern]::Pattern)
    if ($expand) {
        if ($expand.Current.ExpandCollapseState -eq [System.Windows.Automation.ExpandCollapseState]::Expanded) { $expand.Collapse() }
        else { $expand.Expand() }
        return
    }
    if ((Get-Attempt { $element.Current.IsKeyboardFocusable }) -and $null -ne (Get-Attempt { $element.SetFocus(); $true })) { return }
    Stop-Step "the element can't be pressed"
}

function Send-Keys($keys) {
    $chord = Get-Chord $keys
    if (-not $chord) { Stop-Step "the key $($keys.key) is not known" }
    [GuideRecorderReplay.Native]::Press([int[]]$chord.Modifiers, [int]$chord.Key)
}

# Does one step; throws when it can't.
function Invoke-Step($step, $found) {
    switch ($step.kind) {
        'click' {
            Show-Window $found.Window
            Invoke-Element $found.Element
        }
        'rightClick' {
            Show-Window $found.Window
            if ($null -eq (Get-Attempt { $found.Element.SetFocus(); $true })) { Stop-Step "the element can't take the focus to show its menu" }
            [GuideRecorderReplay.Native]::Press([int[]]@(0x10), 0x79)
        }
        'type' {
            Show-Window $found.Window
            if ($null -eq (Get-Attempt { $found.Element.SetFocus(); $true })) { Invoke-Element $found.Element }
            Start-Sleep -Milliseconds 100
            if ($step.keys.type -eq 'text') { [GuideRecorderReplay.Native]::Type([string]$step.keys.text) }
            else { Send-Keys $step.keys }
            if ($step.keys.submit) { [GuideRecorderReplay.Native]::Press([int[]]@(), 0x0D) }
        }
        'shortcut' {
            $el = Get-KeysApp $step
            $app = if ($el.app) { $el.app } else { $el.bundleId }
            $processes = @(Find-Processes $el)
            if ($processes.Count -eq 0) { Stop-Step "$app is not running" }
            # An open menu or dialog of the app keeps the keys.
            $front = [GuideRecorderReplay.Native]::ForegroundProcess()
            if (-not ($processes | Where-Object { $_.Id -eq $front })) {
                $window = Find-AppWindow $el
                if (-not $window) { Stop-Step "$app has no window open" }
                Show-Window $window
            }
            Send-Keys $step.keys
        }
        default { Stop-Step "$($step.kind) steps are not replayed" }
    }
}

function Write-Stop([string]$message) {
    [Console]::Error.WriteLine($message)
    exit 1
}

if ($Guide.guide.recordedOn -eq 'macos') {
    Write-Stop 'This guide was recorded on macOS; replay.ps1 only replays Windows guides (replay.js replays it on a Mac).'
}

$steps = @($Guide.steps | Where-Object { $_.number -ge $From -and $_.number -le $To })
Write-Host "$(if ($DryRun) { 'Dry run of' } else { 'Replaying' }) $(Get-Quoted $Guide.guide.title): $($steps.Count) of $(@($Guide.steps).Count) steps."
$problems = 0
foreach ($step in $steps) {
    $head = "Step $($step.number): $($step.title)"
    $cannot = Get-Unsupported $step
    $needsElement = $step.confidence.level -ne 'notNeeded' -and $step.element
    $found = if ($needsElement -and -not $cannot) { Find-Element $step } else { $null }
    if ($DryRun) {
        $status = 'ok'
        if ($cannot) { $status = "would stop: $cannot" }
        elseif ($found -and $found.Problem) { $status = "not found now: $($found.Problem)" }
        if ($status -ne 'ok') { $problems++ }
        Write-Host "$head`n  would $(Get-Plan $step)`n  $status"
        continue
    }
    $next = "Do it by hand, then run again with -From $($step.number + 1)."
    if ($cannot) { Write-Stop "$head`n  stopped: $cannot. $next" }
    if ($found -and $found.Problem) { Write-Stop "$head`n  stopped: $($found.Problem). $next" }
    try {
        Invoke-Step $step $found
    } catch {
        Write-Stop "$head`n  stopped: $($_.Exception.Message.TrimEnd('.')). $next"
    }
    Write-Host "$head`n  done: $(Get-Plan $step)"
    Start-Sleep -Milliseconds ([int]($Delay * 1000))
}
if ($DryRun) {
    Write-Host $(if ($problems) { "$problems step(s) need attention." } else { 'Every step can be replayed now.' })
} else {
    Write-Host 'Done.'
}
