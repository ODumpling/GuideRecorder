# Virtual-key codes of the named keys in steps.json.
$VirtualKeys = @{
    return = 0x0D; tab = 0x09; space = 0x20; backspace = 0x08; escape = 0x1B; forwardDelete = 0x2E
    left = 0x25; up = 0x26; right = 0x27; down = 0x28; home = 0x24; end = 0x23; pageUp = 0x21; pageDown = 0x22
}
foreach ($n in 1..24) { $VirtualKeys["f$n"] = 0x6F + $n }

# Ctrl, Alt, Shift and the Windows key, as steps.json names them.
$ModifierKeys = @{ control = 0x11; option = 0x12; shift = 0x10; command = 0x5B }
$ModifierNames = @{ control = 'Ctrl'; option = 'Alt'; shift = 'Shift'; command = 'Win' }
# The named keys as Windows labels them.
$KeyNames = @{
    return = 'Enter'; tab = 'Tab'; space = 'Space'; backspace = 'Backspace'; escape = 'Esc'; forwardDelete = 'Delete'
    left = 'Left'; up = 'Up'; right = 'Right'; down = 'Down'; home = 'Home'; end = 'End'; pageUp = 'Page Up'; pageDown = 'Page Down'
}

