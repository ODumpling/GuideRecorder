#!/usr/bin/osascript -l JavaScript
// Replays a GuideRecorder guide on macOS through the accessibility API.
//
//   osascript -l JavaScript replay.js --dry-run     report only, change nothing
//   osascript -l JavaScript replay.js               do the steps
//
// Options:
//   --dry-run     Look up every step's app, window and element and report
//                 what would be done; press, type and activate nothing.
//   --from N      Start at step N (e.g. after doing a step by hand).
//   --to N        Stop after step N.
//   --delay S     Seconds to wait after each step (default 1).
//
// Each step's element is found through System Events: the app (by bundle
// id, else name), then its window (by title), then an element of the
// recorded role whose title, description, name or value is the recorded
// label. Clicks press the element (AXPress), right-clicks show its menu
// (AXShowMenu), typing focuses it and types the text, shortcuts press the
// keys in the app.
//
// The script stops, without acting, at the first step it can't do safely:
// an element that was not identified clearly when recorded, an app, window
// or element it can't find, more than one matching element, a password
// (masked when recorded), a manual step, a double-click or a drag. Do that
// step by hand, then run again with --from and the next step's number.
//
// The app running it (Terminal, or osascript's host) needs Accessibility
// permission: System Settings > Privacy & Security > Accessibility. A dry
// run of a guide only finds the elements already on screen; later steps'
// elements often appear only after earlier steps are done.
//
// Generated by GuideRecorder from the guide below; edit with care.

const GUIDE = __GUIDERECORDER_STEPS__;

// Roles of elements outside any window.
const WINDOWLESS_ROLES = ["AXDockItem", "AXMenuBarItem", "AXMenuItem"];
const MENU_ROLES = ["AXMenuBarItem", "AXMenuItem"];

// macOS virtual key codes of the named keys in steps.json.
const KEY_CODES = {
  return: 36, tab: 48, space: 49, backspace: 51, escape: 53, forwardDelete: 117,
  left: 123, right: 124, down: 125, up: 126, home: 115, end: 119, pageUp: 116, pageDown: 121,
  f1: 122, f2: 120, f3: 99, f4: 118, f5: 96, f6: 97, f7: 98, f8: 100, f9: 101, f10: 109,
  f11: 103, f12: 111, f13: 105, f14: 107, f15: 113, f16: 106, f17: 64, f18: 79, f19: 80, f20: 90,
};

const MODIFIERS = { control: "control down", option: "option down", shift: "shift down", command: "command down" };

class Stop extends Error {}

function parseArgs(argv) {
  const opts = { dryRun: false, from: 1, to: Infinity, delay: 1 };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    const number = () => {
      const value = Number(argv[++i]);
      if (!Number.isFinite(value) || value < 0) throw new Stop(`${arg} needs a number`);
      return value;
    };
    if (arg === "--dry-run") opts.dryRun = true;
    else if (arg === "--from") opts.from = number();
    else if (arg === "--to") opts.to = number();
    else if (arg === "--delay") opts.delay = number();
    else if (arg === "--help" || arg === "-h") opts.help = true;
    else throw new Stop(`unknown option ${arg} (try --help)`);
  }
  return opts;
}

/** Collapses whitespace, as the recorder cleans labels. */
function clean(text) {
  return typeof text === "string" ? text.replace(/\s+/g, " ").trim() : "";
}

/** Calls `get` and returns its value, or null if the element doesn't have it. */
function attempt(get) {
  try {
    const value = get();
    return value === undefined ? null : value;
  } catch (e) {
    return null;
  }
}

function describe(step) {
  const el = step.element || {};
  const parts = [];
  if (el.role || el.label) parts.push(`${el.role || "element"}${el.label ? ` "${el.label}"` : ""}`);
  if (el.window) parts.push(`in window "${el.window}"`);
  if (el.app || el.bundleId) parts.push(`of ${el.app || el.bundleId}`);
  return parts.join(" ");
}

function keysText(keys) {
  if (!keys) return "";
  if (keys.type === "text") return `type ${JSON.stringify(keys.text)}${keys.submit ? " and press Return" : ""}`;
  if (keys.type === "secret") return "type a password";
  return `press ${keys.modifiers.concat([keys.key]).join("+")}`;
}

/** What the step does, in words. */
function plan(step) {
  const target = describe(step);
  switch (step.kind) {
    case "click": return `click ${target}`;
    case "rightClick": return `show the menu of ${target}`;
    case "type": return `${keysText(step.keys)} into ${target}`;
    case "shortcut": return `${keysText(step.keys) || `press ${step.keystrokes || "?"}`}${target ? ` in ${target}` : ""}`;
    case "doubleClick": return `double-click ${target}`;
    case "drag": return `drag ${target}`;
    default: return "do it by hand";
  }
}

/** Why the step can't be replayed at all, or null. */
function unsupported(step) {
  if (step.kind === "manual") return "it is a manual step";
  if (step.kind === "doubleClick") return "double-clicks are not replayed";
  if (step.kind === "drag") return "drags are not replayed";
  if (step.keys && step.keys.type === "secret") return "it types a password, which was masked when recorded";
  if ((step.kind === "type" || step.kind === "shortcut") && !step.keys) return `its keys (${step.keystrokes || "none"}) can't be read`;
  if (step.keys && step.keys.type === "shortcut" && step.keys.key.length > 1 && !(step.keys.key in KEY_CODES)) {
    return `the key ${step.keys.key} is not known`;
  }
  if (step.confidence.level === "low") return `its element is unclear (${step.confidence.issues.join(", ")})`;
  return null;
}

/** The System Events process of the step's app, or null if it isn't running. */
function findProcess(se, el) {
  const matches = el.bundleId ? se.processes.whose({ bundleIdentifier: el.bundleId }) : se.processes.whose({ name: el.app });
  return attempt(() => matches.length) ? matches[0] : null;
}

function findWindow(proc, el) {
  const windows = attempt(() => proc.windows()) || [];
  const found = windows.filter((w) => clean(attempt(() => w.name())) === clean(el.window));
  return found;
}

function labelMatches(candidate, label) {
  return [() => candidate.title(), () => candidate.description(), () => candidate.name(), () => candidate.value()].some(
    (get) => {
      const text = clean(attempt(get));
      // Labels are cut at 200 characters when recorded.
      return text !== "" && (text === label || (label.length >= 200 && text.startsWith(label)));
    },
  );
}

/** The elements that match the step's role and label, searched in `root`. */
function findElements(root, el) {
  const label = clean(el.label);
  const all = attempt(() => root.entireContents()) || [];
  return all.filter((candidate) => attempt(() => candidate.role()) === el.role && labelMatches(candidate, label));
}

/**
 * Looks the step's element up. Returns { element } or { problem }; never
 * activates anything.
 */
function locate(se, step) {
  const el = step.element;
  const proc = findProcess(se, el);
  if (!proc) return { problem: `${el.app || el.bundleId} is not running` };
  let root = proc;
  if (MENU_ROLES.includes(el.role)) {
    root = attempt(() => proc.menuBars[0]) || proc;
  } else if (!WINDOWLESS_ROLES.includes(el.role)) {
    const windows = findWindow(proc, el);
    if (windows.length === 0) return { problem: `no window "${el.window}" is open` };
    if (windows.length > 1) return { problem: `${windows.length} windows are called "${el.window}"` };
    root = windows[0];
  }
  const found = findElements(root, el);
  if (found.length === 0) return { problem: "the element is not there" };
  if (found.length > 1) return { problem: `${found.length} elements match` };
  return { element: found[0] };
}

function activate(el) {
  if (!el || WINDOWLESS_ROLES.includes(el.role) || el.bundleId === "com.apple.dock") return;
  const app = Application(el.bundleId || el.app);
  app.activate();
  delay(0.5);
}

function press(se, keys) {
  const options = keys.modifiers.length ? { using: keys.modifiers.map((m) => MODIFIERS[m]) } : {};
  if (keys.key in KEY_CODES) se.keyCode(KEY_CODES[keys.key], options);
  else se.keystroke(keys.key, options);
}

function perform(element, action) {
  const found = attempt(() => element.actions.byName(action).exists());
  if (!found) throw new Stop(`the element has no ${action} action`);
  element.actions.byName(action).perform();
}

/** Does one step; throws Stop when it can't. */
function act(se, step, element) {
  activate(step.element);
  switch (step.kind) {
    case "click":
      perform(element, "AXPress");
      break;
    case "rightClick":
      perform(element, "AXShowMenu");
      break;
    case "type":
      if (attempt(() => { element.focused = true; return true; }) === null) perform(element, "AXPress");
      if (step.keys.type === "text") se.keystroke(step.keys.text);
      else press(se, step.keys);
      if (step.keys.submit) se.keyCode(KEY_CODES.return);
      break;
    case "shortcut":
      press(se, step.keys);
      break;
    default:
      throw new Stop(`${step.kind} steps are not replayed`);
  }
}

function run(argv) {
  const say = (line) => console.log(line);
  let opts;
  try {
    opts = parseArgs(argv);
  } catch (e) {
    throw new Error(e.message);
  }
  if (opts.help) {
    say("Usage: osascript -l JavaScript replay.js [--dry-run] [--from N] [--to N] [--delay S]");
    return;
  }
  if (GUIDE.guide.recordedOn === "windows") {
    throw new Error("This guide was recorded on Windows; the replay script only replays macOS guides.");
  }
  const se = Application("System Events");
  const steps = GUIDE.steps.filter((s) => s.number >= opts.from && s.number <= opts.to);
  say(`${opts.dryRun ? "Dry run of" : "Replaying"} "${GUIDE.guide.title}": ${steps.length} of ${GUIDE.steps.length} steps.`);
  let problems = 0;
  for (const step of steps) {
    const head = `Step ${step.number}: ${step.title}`;
    const cannot = unsupported(step);
    const needsElement = step.confidence.level !== "notNeeded" && step.element;
    const located = needsElement && !cannot ? locate(se, step) : null;
    if (opts.dryRun) {
      let status = "ok";
      if (cannot) status = `would stop: ${cannot}`;
      else if (located && located.problem) status = `not found now: ${located.problem}`;
      if (status !== "ok") problems++;
      say(`${head}\n  would ${plan(step)}\n  ${status}`);
      continue;
    }
    const next = `Do it by hand, then run again with --from ${step.number + 1}.`;
    if (cannot) throw new Error(`${head}\n  stopped: ${cannot}. ${next}`);
    if (located && located.problem) throw new Error(`${head}\n  stopped: ${located.problem}. ${next}`);
    try {
      act(se, step, located && located.element);
    } catch (e) {
      throw new Error(`${head}\n  stopped: ${e.message}. ${next}`);
    }
    say(`${head}\n  done: ${plan(step)}`);
    delay(opts.delay);
  }
  if (opts.dryRun) say(problems ? `${problems} step(s) need attention.` : "Every step can be replayed now.");
  else say("Done.");
}
