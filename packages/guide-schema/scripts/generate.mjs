// Generates src/guide.gen.ts from guide.schema.json, which the Rust test
// `guide_schema_is_current` writes from guiderecorder_core::model. Run after
// `UPDATE_GOLDEN=1 cargo test -p guiderecorder-core --test guide_schema`.

import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const root = new URL("..", import.meta.url);
const schema = JSON.parse(await readFile(new URL("guide.schema.json", root), "utf8"));

const types = await compile(structuredClone(schema), "Guide", {
  bannerComment: "",
  additionalProperties: false,
  format: false,
});

const source = `// Generated by scripts/generate.mjs from guide.schema.json. Do not edit.

${types.trim()}

/** guide.schema.json, with \`$ref\` siblings moved into \`allOf\` for Zod. */
export const guideJsonSchema = ${JSON.stringify(normalize(schema), null, 2)} as const;
`;
await writeFile(new URL("src/guide.gen.ts", root), source);

/**
 * schemars puts a \`$ref\` next to other keywords (tagged enum variants:
 * \`{ $ref: Step, properties: { type: { const: "step" } } }\`). Zod's
 * \`fromJSONSchema\` ignores such siblings, so wrap them as \`allOf\`.
 */
function normalize(node) {
  if (Array.isArray(node)) return node.map(normalize);
  if (!node || typeof node !== "object") return node;
  const out = Object.fromEntries(Object.entries(node).map(([k, v]) => [k, normalize(v)]));
  const kept = ["$ref", "description", "default"];
  if (out.$ref && Object.keys(out).some((k) => !kept.includes(k))) {
    const { $ref, description, ...rest } = out;
    return { ...(description ? { description } : {}), allOf: [{ $ref }, rest] };
  }
  return out;
}
